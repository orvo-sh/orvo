export const isValidOrganizationSlug = (slug: string) =>
	/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug) &&
	slug.length >= 2 &&
	slug.length <= 64 &&
	!RESERVED_ORGANIZATION_SLUGS.has(slug);
